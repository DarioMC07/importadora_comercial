-- ---------------------------------------------------------------------------
-- Catálogo público: se genera publicando cada producto marcado como tal.
-- (La función copia únicamente los campos autorizados).
-- ---------------------------------------------------------------------------
do $$
declare
  r record;
begin
  -- publish_product exige un miembro autenticado; en seed corremos como owner,
  -- así que insertamos la proyección pública directamente con los mismos campos.
  for r in select p.*, w.public_name, w.slug as wslug
           from public.products p
           join public.seller_workspaces w on w.id = p.workspace_id
           where p.published
  loop
    insert into public.catalog_listings (
      workspace_id, product_id, slug, name, description, category, price,
      availability, origin_country, seller_public_name, seller_slug, images
    ) values (
      r.workspace_id, r.id, public.make_listing_slug(r.name), r.name, r.description,
      r.category, r.sale_price, public.availability_of(r.stock, r.min_stock),
      case when r.origin_public then r.origin_country else null end,
      r.public_name, r.wslug, '[]'::jsonb
    );
  end loop;
end $$;

